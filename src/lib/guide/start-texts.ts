export type PlanChoice = "mushafrev" | "mushaf" | "juzamma" | "custom";

// a saved plan's name, in the words of the plan question
const PLAN_NAME: Record<string, string> = {
  MUSHAF_REVERSE: "من آخر المصحف",
  MUSHAF_ORDER: "من أول المصحف",
  JUZ_AMMA_REVERSE: "جزء عمّ فقط",
  CUSTOM: "خطة مخصّصة",
};

export const planName = (template: string) => PLAN_NAME[template] ?? PLAN_NAME.CUSTOM;

// the summary line is a subject: «بندان», not «بندين»
const ITEMS = { one: "بند واحد", two: "بندان", few: "بنود", many: "بندًا" };

const reviewAfter = (n: number) => (n === 1 ? "بعد يوم واحد" : n === 2 ? "بعد يومين" : n <= 10 ? `بعد ${n} أيام` : `بعد ${n} يومًا`);

/** What the last screen lists: her real data once the questions are done. */
export type SetupSummary = {
  planTemplate: string | null;
  priorSurahs: number;
  // daysLabel() of her commitment days
  commitDays: string;
  trackerItems: number;
  agenda: boolean;
  city: string | null;
  reviewDays: number | null;
};

